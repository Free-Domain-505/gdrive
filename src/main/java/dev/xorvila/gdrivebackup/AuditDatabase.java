package dev.xorvila.gdrivebackup;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.Instant;

/** Embedded H2 database for durable settings snapshots and an audit/console event history. */
final class AuditDatabase {
    private static String jdbcUrl;
    private static Path databaseFile;
    private static volatile boolean ready;

    private AuditDatabase() {}

    static synchronized void initialize(Path configDir) {
        try {
            java.nio.file.Files.createDirectories(configDir);
            Path base = configDir.resolve("gdrivebackup").toAbsolutePath().normalize();
            databaseFile = configDir.resolve("gdrivebackup.mv.db");
            jdbcUrl = "jdbc:h2:file:" + base.toString().replace('\\', '/') + ";DB_CLOSE_ON_EXIT=FALSE;AUTO_SERVER=FALSE;LOCK_TIMEOUT=10000";
            Class.forName("org.h2.Driver");
            try (Connection c = connect(); Statement s = c.createStatement()) {
                s.execute("CREATE TABLE IF NOT EXISTS app_settings (setting_key VARCHAR(100) PRIMARY KEY, setting_value CLOB NOT NULL, updated_at TIMESTAMP NOT NULL)");
                s.execute("CREATE TABLE IF NOT EXISTS event_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_time TIMESTAMP NOT NULL, level VARCHAR(12) NOT NULL, actor VARCHAR(160) NOT NULL, event VARCHAR(100) NOT NULL, detail CLOB NOT NULL)");
                s.execute("CREATE INDEX IF NOT EXISTS idx_event_log_time ON event_log(event_time DESC)");
            }
            ready = true;
            log("INFO", "system", "DATABASE_READY", "Embedded database initialized at " + databaseFile);
        } catch (Exception e) {
            ready = false;
            GDriveBackupMod.LOGGER.error("Could not initialize embedded database", e);
        }
    }

    static Path databaseFile() { return databaseFile; }

    private static Connection connect() throws Exception {
        if (jdbcUrl == null) throw new IllegalStateException("Database is not initialized");
        return DriverManager.getConnection(jdbcUrl, "sa", "");
    }

    static void storeSettings(BackupConfig config) {
        if (!ready) return;
        JsonObject safe = new JsonObject();
        safe.addProperty("enabled", config.enabled);
        safe.addProperty("intervalMinutes", config.intervalMinutes);
        safe.addProperty("retention", config.retention);
        safe.addProperty("driveFolder", config.driveFolder);
        safe.addProperty("clientIdConfigured", configured(config.clientId));
        safe.addProperty("clientSecretConfigured", configured(config.clientSecret));
        safe.addProperty("googleConnected", config.refreshToken != null && !config.refreshToken.isBlank());
        safe.addProperty("publicBaseUrl", config.publicBaseUrl);
        safe.addProperty("callbackPath", config.callbackPath);
        safe.addProperty("oauthPort", config.oauthPort);
        safe.addProperty("autoStartCloudflared", config.autoStartCloudflared);
        safe.addProperty("cloudflaredExecutable", config.cloudflaredExecutable);
        safe.addProperty("cloudflaredTokenConfigured", config.cloudflaredToken != null && !config.cloudflaredToken.isBlank());
        safe.addProperty("dashboardEnabled", config.dashboardEnabled);
        upsertSetting("public_settings", safe.toString());
    }

    private static boolean configured(String value) {
        return value != null && !value.isBlank() && !value.startsWith("YOUR_") && !value.startsWith("PASTE_");
    }

    private static void upsertSetting(String key, String value) {
        if (!ready) return;
        try (Connection c = connect(); PreparedStatement p = c.prepareStatement(
            "MERGE INTO app_settings (setting_key, setting_value, updated_at) KEY(setting_key) VALUES (?, ?, ?)")) {
            p.setString(1, key); p.setString(2, value); p.setTimestamp(3, Timestamp.from(Instant.now())); p.executeUpdate();
        } catch (Exception e) { GDriveBackupMod.LOGGER.warn("Could not persist dashboard settings in database: {}", safeMessage(e)); }
    }

    static void log(String level, String actor, String event, String detail) {
        if (!ready) return;
        String safe = redact(detail == null ? "" : detail);
        try (Connection c = connect(); PreparedStatement p = c.prepareStatement(
            "INSERT INTO event_log(event_time, level, actor, event, detail) VALUES (?, ?, ?, ?, ?)")) {
            p.setTimestamp(1, Timestamp.from(Instant.now()));
            p.setString(2, level == null ? "INFO" : level.toUpperCase());
            p.setString(3, actor == null || actor.isBlank() ? "system" : actor.substring(0, Math.min(160, actor.length())));
            p.setString(4, event == null ? "EVENT" : event.substring(0, Math.min(100, event.length())));
            p.setString(5, safe);
            p.executeUpdate();
        } catch (Exception e) { GDriveBackupMod.LOGGER.warn("Could not write audit event: {}", safeMessage(e)); }
    }

    private static String redact(String value) {
        BackupConfig c = GDriveBackupMod.CONFIG;
        if (c != null) {
            if (c.clientSecret != null && !c.clientSecret.isBlank()) value = value.replace(c.clientSecret, "[REDACTED]");
            if (c.refreshToken != null && !c.refreshToken.isBlank()) value = value.replace(c.refreshToken, "[REDACTED]");
            if (c.cloudflaredToken != null && !c.cloudflaredToken.isBlank()) value = value.replace(c.cloudflaredToken, "[REDACTED]");
        }
        return value.replaceAll("(?i)(client_secret|refresh_token|access_token|cloudflaredToken)\\s*[=:]\\s*[^\\s,}]+", "$1=[REDACTED]");
    }


    static int eventCount() {
        if (!ready) return 0;
        try (Connection c = connect(); Statement s = c.createStatement(); ResultSet rs = s.executeQuery("SELECT COUNT(*) FROM event_log")) {
            return rs.next() ? rs.getInt(1) : 0;
        } catch (Exception e) {
            GDriveBackupMod.LOGGER.warn("Could not count console events: {}", safeMessage(e));
            return 0;
        }
    }

    /** Selects only the oldest overflow. Rows are deleted only after the matching Drive upload succeeds. */
    static ArchiveBatch oldestBatchForArchive(int keepNewest, int maxBatch) {
        JsonArray rows = new JsonArray();
        java.util.List<Long> ids = new java.util.ArrayList<>();
        if (!ready) return new ArchiveBatch(rows, ids);
        int overflow = Math.max(0, eventCount() - Math.max(1, keepNewest));
        int limit = Math.min(overflow, Math.max(1, maxBatch));
        if (limit == 0) return new ArchiveBatch(rows, ids);
        try (Connection c = connect(); PreparedStatement p = c.prepareStatement(
            "SELECT id, event_time, level, actor, event, detail FROM event_log ORDER BY id ASC LIMIT ?")) {
            p.setInt(1, limit);
            try (ResultSet rs = p.executeQuery()) {
                while (rs.next()) {
                    long id = rs.getLong("id");
                    ids.add(id);
                    JsonObject row = new JsonObject();
                    row.addProperty("id", id);
                    row.addProperty("time", rs.getTimestamp("event_time").toInstant().toString());
                    row.addProperty("level", rs.getString("level"));
                    row.addProperty("actor", rs.getString("actor"));
                    row.addProperty("event", rs.getString("event"));
                    row.addProperty("detail", rs.getString("detail"));
                    rows.add(row);
                }
            }
        } catch (Exception e) {
            GDriveBackupMod.LOGGER.warn("Could not prepare console log archive: {}", safeMessage(e));
        }
        return new ArchiveBatch(rows, ids);
    }

    static void deleteArchivedEvents(java.util.List<Long> ids) throws Exception {
        if (!ready || ids == null || ids.isEmpty()) return;
        try (Connection c = connect(); PreparedStatement p = c.prepareStatement("DELETE FROM event_log WHERE id = ?")) {
            for (Long id : ids) { p.setLong(1, id); p.addBatch(); }
            p.executeBatch();
        }
    }

    record ArchiveBatch(JsonArray rows, java.util.List<Long> ids) {}

    static JsonArray recentLogs(int limit) {
        JsonArray rows = new JsonArray();
        if (!ready) return rows;
        int bounded = Math.max(1, Math.min(500, limit));
        try (Connection c = connect(); PreparedStatement p = c.prepareStatement(
            "SELECT id, event_time, level, actor, event, detail FROM event_log ORDER BY id DESC LIMIT ?")) {
            p.setInt(1, bounded);
            try (ResultSet rs = p.executeQuery()) {
                while (rs.next()) {
                    JsonObject row = new JsonObject();
                    row.addProperty("id", rs.getLong("id"));
                    row.addProperty("time", rs.getTimestamp("event_time").toInstant().toString());
                    row.addProperty("level", rs.getString("level"));
                    row.addProperty("actor", rs.getString("actor"));
                    row.addProperty("event", rs.getString("event"));
                    row.addProperty("detail", rs.getString("detail"));
                    rows.add(row);
                }
            }
        } catch (Exception e) { GDriveBackupMod.LOGGER.warn("Could not query audit log: {}", safeMessage(e)); }
        return rows;
    }

    static void close() {
        if (!ready) return;
        try (Connection c = connect(); Statement s = c.createStatement()) { s.execute("SHUTDOWN"); }
        catch (Exception e) { GDriveBackupMod.LOGGER.debug("Database shutdown: {}", safeMessage(e)); }
        ready = false;
    }

    private static String safeMessage(Exception e) { return e.getMessage() == null ? e.getClass().getSimpleName() : e.getMessage(); }
}
